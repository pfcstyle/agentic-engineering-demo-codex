import { expect, test } from '@playwright/test'
test('lead can recover the Version 7 owner-save regression', async ({ page }) => {
  await page.goto('/'); await page.locator('.desktop-queue').getByRole('button', { name: /open incident inc-0003/i }).click()
  const drawer = page.locator('.app-layout .detail-sidebar')
  await drawer.getByLabel('Owner').selectOption('Chen Wei'); await page.getByLabel('Save outcome').selectOption('failure')
  await drawer.getByRole('button', { name: 'Save owner change' }).click(); await expect(drawer.getByRole('alert')).toContainText('not saved')
  await page.getByLabel('Save outcome').selectOption('success'); await drawer.getByRole('button', { name: 'Retry owner change' }).click()
  await expect(drawer.getByText(/saved for this browser session/i)).toBeVisible()
})
